import os
import io
import pandas as pd
import joblib
from fastapi import FastAPI, UploadFile, File
from fastapi.responses import StreamingResponse
from fastapi.middleware.cors import CORSMiddleware
from supabase import create_client, Client
from dotenv import load_dotenv

# Load environment variables (for Supabase)
load_dotenv()

app = FastAPI(title="Parkinson's Diagnostic API")

# --- CORS Configuration ---
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"], 
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# --- Supabase Database Setup ---
SUPABASE_URL = os.getenv("SUPABASE_URL")
SUPABASE_KEY = os.getenv("SUPABASE_KEY")
supabase: Client = None
if SUPABASE_URL and SUPABASE_KEY:
    supabase = create_client(SUPABASE_URL, SUPABASE_KEY)
else:
    print("Warning: Supabase credentials not found. Database logging will be disabled.")

# --- Machine Learning Model Setup ---
try:
    # Load the specific .joblib files generated by your train_model.py
    model = joblib.load("unified_parkinsons_model.joblib") 
    scaler = joblib.load("unified_scaler.joblib")
    expected_features = joblib.load("unified_features.joblib")
    print(f"SUCCESS: Model, Scaler, and {len(expected_features)} specific features loaded!")
except Exception as e:
    print(f"CRITICAL WARNING: Models failed to load. Error: {e}")
    model = None
    scaler = None
    expected_features = []


# --- API ENDPOINTS ---

@app.post("/upload_and_predict")
async def upload_and_predict(file: UploadFile = File(...)):
    if model is None or scaler is None:
        return {"error": "Machine learning model is not loaded on the server."}

    try:
        contents = await file.read()
        df = pd.read_csv(io.BytesIO(contents))

        # 1. Feature Alignment & Validation
        missing_features = [f for f in expected_features if f not in df.columns]
        if missing_features:
            return {"error": f"Invalid CSV file. Missing {len(missing_features)} required acoustic features."}

        model_input_df = df[expected_features].copy()
        scaled_input = scaler.transform(model_input_df)

        # 2. Prediction & Confidence Calculation
        probabilities = model.predict_proba(scaled_input)[0] 
        prediction = model.predict(scaled_input)
        result = int(prediction[0])
        
        # Calculate the exact probability percentage of the diagnosis
        confidence = round(float(probabilities[result]) * 100, 2)
        diagnosis = "Parkinson's Detected" if result == 1 else "Healthy Control"

        # 3. Database Insertion (Supabase)
        if supabase:
            record_to_save = {
                "ai_prediction": result,
                "status": "unverified"
            }
            if "id" in df.columns and not pd.isna(df["id"].iloc[0]):
                record_to_save["id"] = int(df["id"].iloc[0])
            if "gender" in df.columns and not pd.isna(df["gender"].iloc[0]):
                record_to_save["gender"] = int(df["gender"].iloc[0])
                
            try:
                supabase.table("patient_data").insert(record_to_save).execute()
                log_message = "Data analyzed and logged to database."
            except Exception as db_err:
                print(f"Supabase error: {db_err}")
                log_message = "Data analyzed (Database log failed)."
        else:
            log_message = "Data analyzed (Database disconnected)."

        # 4. Return Final Output to React
        return {
            "filename": file.filename,
            "prediction_code": result,
            "diagnosis": diagnosis,
            "confidence": confidence,
            "message": log_message
        }

    except Exception as e:
        return {"error": f"Processing failed: {str(e)}"}


@app.get("/download_template")
def download_template():
    # Combine 'id', 'gender', and the curated feature list from your model
    columns = ["id", "gender"] + list(expected_features)
    df_empty = pd.DataFrame(columns=columns)
    
    # Write empty dataframe to a string buffer
    stream = io.StringIO()
    df_empty.to_csv(stream, index=False)
    
    # Send the file to the user's browser for download
    response = StreamingResponse(iter([stream.getvalue()]), media_type="text/csv")
    response.headers["Content-Disposition"] = "attachment; filename=blank_patient_template.csv"
    return response