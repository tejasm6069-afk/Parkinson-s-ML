@app.post("/upload_and_predict")
async def upload_and_predict(file: UploadFile = File(...)):
    if model is None or scaler is None:
        return {"error": "Machine learning model is not loaded on the server."}

    try:
        contents = await file.read()
        df = pd.read_csv(io.BytesIO(contents))

        # 1. Feature Alignment & Validation
        missing_features = [f for f in expected_features if f not in df.columns]
        if missing_features:
            return {"error": f"Invalid CSV file. Missing {len(missing_features)} required acoustic features."}

        model_input_df = df[expected_features].copy()
        scaled_input = scaler.transform(model_input_df)

        # 2. Prediction & Confidence Calculation
        probabilities = model.predict_proba(scaled_input)[0] 
        prediction = model.predict(scaled_input)
        result = int(prediction[0])
        
        # Calculate the exact probability percentage of the diagnosis
        confidence = round(float(probabilities[result]) * 100, 2)
        diagnosis = "Parkinson's Detected" if result == 1 else "Healthy Control"

        # 3. Database Insertion (Supabase)
        if supabase:
            record_to_save = {
                "ai_prediction": result,
                "status": "unverified"
            }
            if "id" in df.columns and not pd.isna(df["id"].iloc[0]):
                record_to_save["id"] = int(df["id"].iloc[0])
            if "gender" in df.columns and not pd.isna(df["gender"].iloc[0]):
                record_to_save["gender"] = int(df["gender"].iloc[0])
                
            try:
                supabase.table("patient_data").insert(record_to_save).execute()
                log_message = "Data analyzed and logged to database."
            except Exception as db_err:
                print(f"Supabase error: {db_err}")
                log_message = "Data analyzed (Database log failed)."
        else:
            log_message = "Data analyzed (Database disconnected)."

        # 4. Return Final Output to React
        return {
            "filename": file.filename,
            "prediction_code": result,
            "diagnosis": diagnosis,
            "confidence": confidence,
            "message": log_message
        }

    except Exception as e:
        return {"error": f"Processing failed: {str(e)}"}


